    double F_Amount = 0.0;
    double APY = 0.0;
    int MonthlyC = 0;
    int NoMonths = 0;
    double Total = 0;
    
    
    private void Calculator(){
        double MonthlyRate = Math.pow(1 + APY / 100.0, 1.0 / 12) -1;
        Total = F_Amount;
        
        for (int NUM  = 0; NUM < NoMonths; NUM++){
            Total = Total * (1 + MonthlyRate) + MonthlyC;
        }
        Output_Box.setText(String.format("%.2f", Total));
    }
    

